from app.core.llm_client import _call_llm
from app.core.utils import _parse_json_response, _clamp

def evaluate_faithfulness(
    question: str,
    answer: str,
    context: list,
) -> dict:
    """
    Evaluate whether every claim in the generated answer is grounded in the
    retrieved context (i.e. can be directly inferred from it).

    Scoring approach
    ----------------
    1. Ask the LLM to decompose the answer into atomic factual claims.
    2. For each claim, check whether it is supported by the context.
    3. faithfulness_score = supported_claims / total_claims  (range 0–1)

    Parameters
    ----------
    question : str         – the original user question.
    answer   : str         – the answer generated by the RAG pipeline.
    context  : list[str]   – retrieved text chunks used to generate the answer.

    Returns
    -------
    dict with keys:
        score          (float) – faithfulness score in [0, 1]
        total_claims   (int)   – number of atomic claims extracted
        supported      (int)   – claims verifiably grounded in context
        unsupported    (int)   – claims not found in context
        claim_verdicts (list)  – per-claim breakdown
        reasoning      (str)   – brief explanation
    """
    context_block = "\n\n".join(
        f"[Chunk {i+1}]: {chunk}" for i, chunk in enumerate(context)
    )

    # ── Step 1: extract atomic claims ──────────────────────────────────────
    claims_system = (
        "You are a precise fact-extractor. "
        "Return ONLY a valid JSON object with key 'claims' (list of strings). "
        "No markdown fences, no extra text outside the JSON."
    )
    claims_prompt = (
        f"Decompose the following ANSWER into individual, atomic factual claims.\n\n"
        f"QUESTION: {question}\n\n"
        f"ANSWER: {answer}\n\n"
        'Return exactly: {"claims": ["claim 1", "claim 2", ...]}'
    )
    claims_raw  = _call_llm(claims_system, claims_prompt)
    claims_data = _parse_json_response(claims_raw)
    claims      = claims_data.get("claims", [answer])   # fallback: whole answer as one claim

    if not claims:
        return {
            "score": 0.0,
            "total_claims": 0,
            "supported": 0,
            "unsupported": 0,
            "claim_verdicts": [],
            "reasoning": "No claims could be extracted from the answer.",
        }

    # ── Step 2: verify each claim against context ───────────────────────────
    verdict_system = (
        "You are a strict fact-checker for RAG pipelines. "
        "Return ONLY a valid JSON object. No markdown, no extra text."
    )
    verdicts: list[dict] = []

    for claim in claims:
        verdict_prompt = (
            f"CONTEXT:\n{context_block}\n\n"
            f"CLAIM: {claim}\n\n"
            "Is this claim FULLY supported by the context above?\n"
            'Return exactly: {"supported": true or false, "reason": "brief explanation"}'
        )
        verdict_raw  = _call_llm(verdict_system, verdict_prompt)
        verdict_data = _parse_json_response(verdict_raw)
        verdicts.append({
            "claim":     claim,
            "supported": bool(verdict_data.get("supported", False)),
            "reason":    verdict_data.get("reason", ""),
        })

    supported_count   = sum(1 for v in verdicts if v["supported"])
    unsupported_count = len(verdicts) - supported_count
    score             = _clamp(supported_count / len(verdicts))

    return {
        "score":          round(score, 4),
        "total_claims":   len(verdicts),
        "supported":      supported_count,
        "unsupported":    unsupported_count,
        "claim_verdicts": verdicts,
        "reasoning":      (
            f"{supported_count}/{len(verdicts)} claims are supported by the retrieved context."
        ),
    }
