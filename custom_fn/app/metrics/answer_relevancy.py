import statistics

from app.core.llm_client import _call_llm
from app.core.utils import _parse_json_response, _clamp

def evaluate_answer_relevancy(
    question: str,
    answer: str,
) -> dict:
    """
    Measure how well the generated answer addresses the user's question.

    Scoring approach
    ----------------
    Reverse-question generation: ask the LLM to generate N questions that the
    given answer could be responding to, then score the semantic alignment of
    each synthesised question with the original question.
    score = mean(similarities)  (range 0–1)

    Parameters
    ----------
    question : str – the original user question.
    answer   : str – the answer generated by the RAG pipeline.

    Returns
    -------
    dict with keys:
        score               (float) – relevancy score in [0, 1]
        generated_questions (list)  – questions the answer could address
        similarities        (list)  – per-question similarity scores
        reasoning           (str)   – brief explanation
    """
    system = (
        "You are an expert evaluator of question-answer pairs. "
        "Return ONLY a valid JSON object. No markdown, no extra text."
    )
    prompt = (
        f"ORIGINAL QUESTION: {question}\n\n"
        f"ANSWER: {answer}\n\n"
        "Tasks:\n"
        "1. Generate 3 questions that this ANSWER seems to be responding to.\n"
        "2. For each generated question score its semantic similarity to the "
        "ORIGINAL QUESTION on a scale 0.0–1.0 (1.0 = identical meaning).\n"
        "3. Provide a brief overall explanation.\n\n"
        "Return exactly:\n"
        '{"generated_questions": ["q1", "q2", "q3"], '
        '"similarities": [0.0, 0.0, 0.0], '
        '"reasoning": "explanation"}'
    )
    raw  = _call_llm(system, prompt)
    data = _parse_json_response(raw)

    generated = data.get("generated_questions", [])
    sims      = [_clamp(float(s)) for s in data.get("similarities", [])]
    reasoning = data.get("reasoning", "")

    score = _clamp(statistics.mean(sims)) if sims else 0.0

    return {
        "score":               round(score, 4),
        "generated_questions": generated,
        "similarities":        [round(s, 4) for s in sims],
        "reasoning":           reasoning,
    }
